#!/bin/sh
#
# Regenerate datasets.tsv from a Geant4 installation.
#
#   ./update-datasets.sh [/path/to/geant4-config] > datasets.new.tsv
#
# geant4-config carries the dataset table inside itself as a single awk literal
# of  name|variable|absolute-path|archive|md5  records separated by semicolons.
# That literal is the authority -- it is what `geant4-config --check-datasets`
# verifies against and what `--install-datasets` downloads -- so the table is
# read out of the script rather than recomposed from `--datasets`, whose output
# drops the archive name and the MD5.
#
# The "required" column and the descriptions cannot come from Geant4; they are
# carried over from the existing datasets.tsv by variable name, and a dataset
# that is new since the last run is emitted with required=0 and an empty
# description for you to fill in.
#
# Two files are generated from the result and have to be regenerated with it:
# windows/datasets.nsh and pascal/src/ustratadatasets.pas.  See README.md.

set -eu

config=${1:-$(command -v geant4-config || true)}
here=$(cd "$(dirname "$0")" && pwd)
old=$here/datasets.tsv

if [ -z "$config" ] || [ ! -r "$config" ]; then
    echo "update-datasets.sh: no readable geant4-config (pass its path)" >&2
    exit 1
fi

version=$("$config" --version)

# The literal, as one record per line.
records=$(
    sed -n 's/.*split( "\([^"]*\)", array, ";").*/\1/p' "$config" | tr ';' '\n'
)

if [ -z "$records" ]; then
    echo "update-datasets.sh: no dataset table found in $config" >&2
    exit 1
fi

printf '# Geant4 %s datasets -- the single source of truth for all three installers.\n' "$version"
printf '#\n'
printf '# Generated by update-datasets.sh from %s; do not edit the rows by hand.\n' "$config"
printf '#\n'
printf '# Fields, tab separated:\n'
printf '#   directory  variable  archive  md5  required  description\n'
printf '#\n'

echo "$records" | while IFS='|' read -r name var path archive md5; do
    [ -n "$var" ] || continue
    dir=$(basename "$path")
    required=0
    desc=
    if [ -r "$old" ]; then
        line=$(awk -F'\t' -v v="$var" '$2 == v { print $5 "\t" $6 }' "$old")
        if [ -n "$line" ]; then
            required=$(printf '%s' "$line" | cut -f1)
            desc=$(printf '%s' "$line" | cut -f2)
        fi
    fi
    printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$dir" "$var" "$archive" "$md5" "$required" "$desc"
done
